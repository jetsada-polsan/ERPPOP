const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const pending = [];
const sandbox = { window: {}, URLSearchParams, fetch: (url) => new Promise(resolve => pending.push({ url, resolve })) };
vm.runInNewContext(fs.readFileSync('public/stock-preview.js', 'utf8'), sandbox);
(async () => {
    const model = sandbox.window.erpStockPreview([], '/stock');
    model.branchId = '1';
    const item = { product_id: 20 };
    model.items = [item];
    const first = model.previewStock(item);
    assert.match(pending[0].url, /branch_id=1/);
    model.branchId = '2'; model.locationId = '7';
    const second = model.previewStock(item);
    assert.match(pending[1].url, /warehouse_location_id=7/);
    pending[1].resolve({ ok: true, json: async () => ({ on_hand_qty: 12.5, average_cost: 37.25 }) });
    await second;
    assert.equal(item.average_cost, 37.25);
    assert.equal(item.systemQty, 12.5);
    assert.equal(model.stockPreviewReady(), true);
    pending[0].resolve({ ok: true, json: async () => ({ on_hand_qty: 999, average_cost: 999 }) });
    await first;
    assert.equal(item.systemQty, 12.5, 'Old branch response must not replace selected branch');
    const third = model.previewStock(item);
    pending[2].resolve({ ok: false });
    await third;
    assert.equal(item.previewReady, false);
    assert.equal(item.systemQty, null);
    assert.equal(model.stockPreviewReady(), false, 'Failed lookup must block submission');
    console.log('Passed stock preview values, branch/location requests, stale response and failure checks');
})().catch(e => { console.error(e); process.exit(1); });
